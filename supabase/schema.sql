create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  certificate_id text unique not null,
  participant_name text not null,
  event_name text not null default 'Game On: Imagine The Impossible',
  created_at timestamptz not null default now()
);
alter table public.certificates enable row level security;
-- Public self-service issuance: users may create a certificate record.
-- Public verification: users may read certificate records.
-- For production, add rate limiting / CAPTCHA and restrict exposed columns.
create policy "public can issue certificates" on public.certificates for insert to anon with check (
  length(participant_name) between 2 and 70 and length(certificate_id) between 8 and 40
);
create policy "public can verify certificates" on public.certificates for select to anon using (true);
